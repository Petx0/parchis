"""PILA-5: harvest a 20-round continuation from S1, then soup its trajectory (docs/RESEARCH_BACKLOG.md #2).

Usage: run_harvest.py --base <10_000_000*n> [--run-id pila5_harvest_s1] [--phase all|train|post]
                      [--rounds 20] [--scratch ~/parchis_scratch/pila5_harvest] [--issue PILA-5]
                      [--workers 8] [--pairs 2000] [--health-games 1500] [--smoke]

1. train  The exact V2.1c recipe (scripts/v2/run_v2_1c.py; the run_window.py win3 control): 6,000
          games/round, deep_fraction 0.25 at depth 2 with deep targets and afterstate rows, replay
          window 3, 8 workers, gate off (every candidate adopted), `--rounds` rounds, warm-started from
          soup S1 (runs/soups_2026-11-16/s1/model.pt). Seeds: generation base + round*1000 + shard,
          train base, promotion base + round. Scratch run dir (shards, ~2.4 GB/round) under --scratch.
          Resumable: re-running picks up at the first unfinished round.
2. post   a. Curate the scratch run into runs/<run_id>/ (python -m parchis.registry curate) and copy
             every round's candidate.pt to runs/<run_id>/candidates/cNN.pt (round r -> c{r+1}).
          b. Build the soups of soup_plan() into runs/<run_id>/soups/<name>/model.pt:
             h1 = avg(S1, c10, c20); h2 = avg(c11..c20) (SWA-10); h3 = 0.5*S1 + 0.5*h2;
             h4 = avg(c1..c20) (SWA-20). (Halves scale with --rounds.)
          c. Health check: --health-games fresh games of the same recipe generated by S1
             (seeds base + 500_000 + i), value log-loss of S1, every candidate and every soup; a soup
             worse than its worst direct ingredient by > 0.01 is dropped before any match.
          d. Screening: every kept soup and the endpoint c20 vs S1, --pairs duplicate pairs at depth 1
             on the SAME deals (seeds base + 1_000_000 + c, c < workers: the run's training band, never
             the 5M-10M evaluation band). Ranking only: the winner is a best-of-N pick and the verdict
             is the Evaluator's protocol run (--selection best-of-N) plus a confirmation block.
             Kill criterion: every soup below 50% vs S1 -> no winner, record the null.
          e. Run records: runs/<run_id>/meta.json (the endpoint, with its screening eval),
             soups/<name>/meta.json per soup, health_check.json, screening.json, harvest.json.

Takes ~/parchis_compute.lock for the whole job (exits 3 if held by a live PID), except --smoke.
--smoke: 4 rounds of 40 games on 2 workers, 20 pairs, run id smoke_pila5 (light; delete afterwards).
"""
import argparse
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "scripts/v2"))
import soup_experiment as SE  # noqa: E402

S1 = REPO / "runs/soups_2026-11-16/s1/model.pt"
DEPTH = SE.DEPTH
HEALTH_OFFSET = 500_000
SCREEN_OFFSET = SE.SCREEN_OFFSET            # 1_000_000
TRAINING_BASE_UNIT = SE.TRAINING_BASE_UNIT
ROUND_MINUTES = 5                           # win3: 20 rounds in 97 min


def cand(r):
    """Label of the candidate trained in 1-based round r."""
    return f"c{r:02d}"


def soup_plan(rounds):
    """name -> dict(ingredients=[labels], weights=None|[...], what=...). Labels: 's1', 'cNN', or an
    earlier soup's name. Order matters: a soup may use soups listed before it."""
    if rounds < 4 or rounds % 2:
        raise ValueError("rounds must be even and >= 4")
    half = rounds // 2
    return {
        "h1": dict(ingredients=["s1", cand(half), cand(rounds)], weights=None,
                   what=f"avg(S1, {cand(half)}, {cand(rounds)}): the S1 shape (start + two trajectory points)"),
        "h2": dict(ingredients=[cand(r) for r in range(half + 1, rounds + 1)], weights=None,
                   what=f"SWA-{rounds - half}: avg({cand(half + 1)}..{cand(rounds)})"),
        "h3": dict(ingredients=["s1", "h2"], weights=[0.5, 0.5], what="0.5*S1 + 0.5*h2"),
        "h4": dict(ingredients=[cand(r) for r in range(1, rounds + 1)], weights=None,
                   what=f"SWA-{rounds}: avg({cand(1)}..{cand(rounds)})"),
    }


def screened(rounds):
    """The nets screened vs S1, in order: every soup, then the endpoint."""
    return list(soup_plan(rounds)) + [cand(rounds)]


def recipe(base, run_id, rounds_cfg=None):
    """The V2.1c recipe, window 3, on the allocated seed base (soup_experiment.recipe_config)."""
    cfg = SE.recipe_config(base, run_name=run_id)
    cfg.replay_window_rounds = 3
    for k, v in (rounds_cfg or {}).items():
        setattr(cfg, k, v)
    return cfg


def harvest_candidates(scratch_run_dir, out_dir, rounds):
    """Copy rounds/round_{r-1:04d}/candidate.pt to <out_dir>/candidates/cNN.pt for r = 1..rounds.
    Every round must be complete (done.json). Returns label -> Path."""
    from parchis.az import round_loop
    out = Path(out_dir) / "candidates"
    out.mkdir(parents=True, exist_ok=True)
    paths = {}
    for r in range(1, rounds + 1):
        rd = round_loop._round_dir(scratch_run_dir, r - 1)
        if not round_loop._is_round_complete(rd) or not (rd / "candidate.pt").exists():
            raise FileNotFoundError(f"round {r - 1} not complete or no candidate.pt in {rd}")
        paths[cand(r)] = out / f"{cand(r)}.pt"
        shutil.copy2(rd / "candidate.pt", paths[cand(r)])
    return paths


def build_soups(plan, nets, soups_dir, issue):
    """make_soup for every entry of plan; `nets` maps labels to paths and gains each soup."""
    from parchis.az import soup
    cfgs = {}
    for name, spec in plan.items():
        out = Path(soups_dir) / name / "model.pt"
        cfgs[name] = soup.make_soup(out, [nets[i] for i in spec["ingredients"]], spec["weights"], name=name,
                                    extra=dict(issue=issue, ingredient_names=spec["ingredients"], what=spec["what"]))
        nets[name] = out
    return cfgs


def pick_winner(screening, soups):
    """(ranking, winner, killed). Kill: every screened soup below 50% -> no winner."""
    ranked = sorted(screening, key=lambda k: -screening[k]["win_rate"])
    killed = not any(screening[s]["win_rate"] > 0.5 for s in soups if s in screening)
    winner = None if killed or not ranked or screening[ranked[0]]["win_rate"] <= 0.5 else ranked[0]
    return ranked, winner, killed


def _rel(p):
    from parchis.registry import record as registry
    return registry.rel(p)


def train(a, base, run_id, scratch, overrides):
    import torch
    from parchis.az import round_loop
    cfg = recipe(base, run_id, overrides)
    init = torch.load(S1, map_location="cpu")
    t0 = time.time()
    round_loop.run_continuous(cfg, runs_dir=str(scratch), max_rounds=a.rounds, initial_champion_state_dict=init,
                              record=dict(issue=a.issue, init_path=str(S1),
                                          title=f"{a.issue} harvest: {a.rounds} rounds of the V2.1c recipe "
                                                f"(window 3) from soup S1, every candidate kept",
                                          notes="Candidates in candidates/, soups of the trajectory in soups/; "
                                                "harvest.json summarises the post phase."))
    print(f"== train: {a.rounds} rounds done, {(time.time() - t0) / 60:.1f} min", flush=True)
    return time.time() - t0


def post(a, base, run_id, scratch, overrides, seed_entry):
    import torch
    from parchis.az import soup
    from parchis.registry import record as registry
    t0 = time.time()
    run_dir = REPO / "runs" / run_id
    scratch_run = scratch / run_id
    # a. curate + candidates
    subprocess.run([sys.executable, "-m", "parchis.registry", "curate", str(scratch_run), run_id,
                    "--issue", a.issue], cwd=REPO, check=True)
    nets = dict(s1=S1, **harvest_candidates(scratch_run, run_dir, a.rounds))
    end = cand(a.rounds)
    sd_end, sd_model = (torch.load(p, map_location="cpu") for p in (nets[end], run_dir / "model.pt"))
    endpoint_is_model = list(sd_end) == list(sd_model) and all(torch.equal(sd_end[k], sd_model[k]) for k in sd_end)
    print(f"candidates: {len(nets) - 1} copied; {end} == model.pt: {endpoint_is_model}", flush=True)
    # b. soups
    plan = soup_plan(a.rounds)
    cfgs = build_soups(plan, nets, run_dir / "soups", a.issue)
    for name in plan:
        print(f"soup {name} = {plan[name]['what']} sha256 {cfgs[name]['output']['sha256'][:12]}", flush=True)
    # c. health check
    cfg = recipe(base, run_id + "_health", overrides)
    hscratch = scratch / "health"
    hscratch.mkdir(parents=True, exist_ok=True)
    tg = time.time()
    shard_paths, shard_info = SE.generate_health_shards(cfg, base + HEALTH_OFFSET, a.health_games, a.workers,
                                                        hscratch, generator=S1)
    gen_s = time.time() - tg
    data = soup.load_shards(shard_paths)
    losses = {}
    for key in ["s1"] + [cand(r) for r in range(1, a.rounds + 1)] + list(plan):
        losses[key] = soup.shard_losses(torch.load(nets[key], map_location="cpu"), data)
        print(f"  {key:4s} value {losses[key]['value_loss']:.5f}  policy {losses[key]['policy_loss']:.5f}", flush=True)
    health = {}
    for name, spec in plan.items():
        ing = [losses[i]["value_loss"] for i in spec["ingredients"]]
        keep = soup.health_verdict(losses[name]["value_loss"], ing)
        health[name] = dict(value_loss=losses[name]["value_loss"], worst_ingredient=max(ing),
                            best_ingredient=min(ing), margin=soup.HEALTH_MARGIN, keep=keep,
                            delta_vs_worst=losses[name]["value_loss"] - max(ing),
                            delta_vs_best=losses[name]["value_loss"] - min(ing))
        print(f"health {name}: Δ vs worst {health[name]['delta_vs_worst']:+.5f} -> {'keep' if keep else 'DROP'}",
              flush=True)
    (run_dir / "health_check.json").write_text(json.dumps(dict(
        issue=a.issue, recipe="V2.1c (scripts/v2/run_v2_1c.py), window 3", generator=_rel(S1),
        generator_sha256=registry.file_sha256(S1), games=sum(s["n_games"] for s in shard_info),
        shards=[dict(s, path=_rel(s["path"])) for s in shard_info],
        seeds=f"{base + HEALTH_OFFSET}+i, i<{len(shard_info)}", generation_s=round(gen_s, 1),
        rows=losses["s1"]["n_rows"], decision_rows=losses["s1"]["n_decision_rows"], losses=losses, verdicts=health,
        caveat="data generated by S1 with S1 depth-2 deep targets: biased towards S1's own value head"),
        indent=2) + "\n")
    # d. screening
    seeds = [base + SCREEN_OFFSET + c for c in range(a.workers)]
    screening = {}
    for name in screened(a.rounds):
        if name in health and not health[name]["keep"]:
            continue
        ts = time.time()
        r = SE.screen(nets[name], seeds, a.pairs, opponent=S1)
        r.update(seeds=f"{seeds[0]}+c, c<{len(seeds)} (same deals for every net)", depth=DEPTH, pairs=a.pairs,
                 wall_clock_s=round(time.time() - ts, 1), opponent=_rel(S1))
        screening[name] = r
        print(f"screen {name} vs S1: {r['win_rate']:.4f} [{r['ci'][0]:.4f}, {r['ci'][1]:.4f}] n={r['n_games']} "
              f"draws={r['draws']} ({r['wall_clock_s']:.0f}s)", flush=True)
    ranked, winner, killed = pick_winner(screening, list(plan))
    (run_dir / "screening.json").write_text(json.dumps(dict(
        issue=a.issue, opponent=_rel(S1), depth=DEPTH, pairs=a.pairs, seeds=[seeds[0], seeds[-1]],
        results=screening, dropped_by_health=[n for n in plan if not health[n]["keep"]], ranking=ranked,
        winner=winner, killed=killed,
        kill_criterion="every soup below 50% vs S1 -> stop after screening, record the null",
        note=f"ranking only; the winner is best-of-{len(screening)} and needs the protocol "
             f"(--selection best-of-{len(screening)}) + confirmation; {end} vs S1 is the §10.11 endpoint replicate"),
        indent=2) + "\n")
    # e. run records
    wall_post = time.time() - t0
    n = len(screening)
    path_of = {k: (run_dir / "soups" / k if k in plan else run_dir) for k in screened(a.rounds)}

    def selection(name):
        if name == winner:
            return dict(method=f"best-of-{n}", chosen="highest screening score vs S1", n=n,
                        candidates=[_rel(path_of[k]) for k in ranked], source=_rel(run_dir / "screening.json"),
                        note=f"screening seeds in the run's training band; protocol needs --selection best-of-{n} "
                             "and a confirmation run")
        if name in health and not health[name]["keep"]:
            return dict(method="dropped", reason="health check: value loss > worst ingredient + 0.01")
        return dict(method="not selected", rank=ranked.index(name) + 1, of=n, source=_rel(run_dir / "screening.json"),
                    reason="kill criterion: no soup above 50% in screening" if killed else None)

    def screening_eval(meta, name, ckpt):
        if name in screening:
            s = screening[name]
            registry.add_eval(meta, registry.eval_entry(
                "h2h", ckpt, S1, s["win_rate"], s["ci"], s["n_games"], seeds=s["seeds"], depth=DEPTH,
                source=run_dir / "screening.json", tag="pila5_screening", draws=s["draws"],
                wall_clock_s=s["wall_clock_s"], note="screening only (ranks the harvest nets); not a verdict"))

    for name, spec in plan.items():
        sdir = run_dir / "soups" / name
        config = dict(method="weight average (model soup) of the harvest trajectory, no gradient steps",
                      ingredients=cfgs[name]["ingredients"], weights=spec["weights"], what=spec["what"],
                      generation_seed=base, train_seed=base, promotion_seed=base,
                      seed_use=(f"health-check shards base+{HEALTH_OFFSET}+i; screening deals base+{SCREEN_OFFSET}+c; "
                                "the trajectory itself was trained on this base (parent run)"))
        meta = registry.new_meta(f"{run_id}/soups/{name}", "training", config=config, issue=a.issue,
                                 title=f"{a.issue} harvest soup {name.upper()} = {spec['what']}", init=None,
                                 script=_rel(__file__), command=" ".join(sys.argv),
                                 notes=f"Soup of the {run_id} trajectory; see ../../harvest.json.")
        meta["init"] = dict(note="weight average of the ingredients in config.ingredients", path=None, sha256=None,
                            run_id=run_id)
        meta["seeds"]["registered_to"] = [seed_entry["run_id"]]
        meta["training"] = dict(rounds_completed=0, selfplay_games=0, wall_clock_s=round(wall_post, 1),
                                note=f"no training: weights averaged; trained trajectory in ../../ ({run_id})")
        meta["health_check"] = health[name]
        meta["selection"] = selection(name)
        meta["status"], meta["finished"] = "finished", registry.now()
        meta["sessions"] = [dict(started=meta["created"], git_sha=meta["git"]["sha"], git_dirty=meta["git"]["dirty"],
                                 command=meta["command"])]
        registry.set_checkpoint(meta, registry.checkpoint_entry(sdir / "model.pt", role="final", label=name))
        screening_eval(meta, name, sdir / "model.pt")
        registry.save_meta(sdir, meta)

    def mutate(m):
        for r in range(1, a.rounds + 1):
            registry.set_checkpoint(m, registry.checkpoint_entry(run_dir / "candidates" / f"{cand(r)}.pt",
                                                                 role="candidate", label=cand(r), primary=False,
                                                                 round=r - 1))
        screening_eval(m, end, run_dir / "model.pt")
        m["selection"] = (dict(selection(end), endpoint="model.pt is the champion after the last round "
                                                         f"(ungated; same tensors as {end}: {endpoint_is_model})")
                          if end in screening else m.get("selection"))
        m["status"], m["finished"] = "finished", m.get("finished") or registry.now()
    registry.update_run(run_dir, mutate)
    summary = dict(issue=a.issue, run_id=run_id, start=dict(path=_rel(S1), sha256=registry.file_sha256(S1)),
                   seed_base=base, rounds=a.rounds, endpoint=end, endpoint_is_model_pt=endpoint_is_model,
                   candidates={k: dict(path=_rel(v), sha256=registry.file_sha256(v)) for k, v in nets.items()
                               if k.startswith("c")},
                   soups={k: dict(spec, path=_rel(nets[k]), sha256=cfgs[k]["output"]["sha256"]) for k, spec in plan.items()},
                   health={k: v["keep"] for k, v in health.items()}, screening={k: dict(win_rate=v["win_rate"], ci=v["ci"],
                   n_games=v["n_games"]) for k, v in screening.items()}, ranking=ranked, winner=winner, killed=killed,
                   winner_path=_rel(path_of[winner] / "model.pt") if winner else None,
                   post_wall_clock_s=round(wall_post, 1), health_generation_s=round(gen_s, 1))
    (run_dir / "harvest.json").write_text(json.dumps(summary, indent=2) + "\n")
    for d in [run_dir] + [run_dir / "soups" / k for k in plan]:
        problems = registry.validate(registry.load_meta(d))
        print(f"record {_rel(d)}: " + ("OK" if not problems else "INCOMPLETE " + "; ".join(problems)), flush=True)
    print(f"winner: {winner or 'none'}{' (kill criterion met)' if killed else ''}   ranking {ranked}   "
          f"post wall-clock {wall_post:.0f}s", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", type=int, required=True)
    ap.add_argument("--run-id", default="pila5_harvest_s1")
    ap.add_argument("--phase", choices=("all", "train", "post"), default="all")
    ap.add_argument("--rounds", type=int, default=20)
    ap.add_argument("--scratch", default=str(Path.home() / "parchis_scratch/pila5_harvest"))
    ap.add_argument("--issue", default="PILA-5")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--pairs", type=int, default=2000)
    ap.add_argument("--health-games", type=int, default=1500)
    ap.add_argument("--smoke", action="store_true")
    a = ap.parse_args()
    overrides = {}
    if a.smoke:
        a.run_id, a.rounds, a.workers, a.pairs, a.health_games = "smoke_pila5", 4, 2, 20, 20
        a.scratch = str(Path(a.scratch).expanduser() / "smoke")
        overrides = dict(n_games_per_round=40, games_per_shard=20, generation_workers=2, promotion_n_pairs=4)
    if a.base < TRAINING_BASE_UNIT or a.base % TRAINING_BASE_UNIT:
        print(f"--base must be a positive multiple of {TRAINING_BASE_UNIT}", file=sys.stderr)
        return 4
    soup_plan(a.rounds)                     # validates --rounds
    from parchis.registry import record as registry
    seed_entry = next((e for r in (registry.HOME_SEED_REGISTRY, registry.REPO_SEED_REGISTRY)
                       for e in registry._read_jsonl(r) if e.get("kind") == "training" and e.get("base") == a.base), None)
    if seed_entry is None:
        print(f"base {a.base} is not allocated in the seed registry (python -m parchis.registry alloc-seed)",
              file=sys.stderr)
        return 4
    scratch = Path(a.scratch).expanduser()
    scratch.mkdir(parents=True, exist_ok=True)
    if not a.smoke:
        eta = (a.rounds * ROUND_MINUTES if a.phase != "post" else 0) + (15 if a.phase != "train" else 0)
        held = SE.acquire_lock(a.issue, f"{a.issue} harvest from S1: {a.phase} ({a.rounds} rounds, "
                                        f"{len(screened(a.rounds))}x{a.pairs} screening pairs)", eta_minutes=eta)
        if held:
            print(f"compute lock held: {held}", flush=True)
            return 3
    try:
        if a.phase in ("all", "train"):
            train(a, a.base, a.run_id, scratch, overrides)
        if a.phase in ("all", "post"):
            post(a, a.base, a.run_id, scratch, overrides, seed_entry)
    finally:
        if not a.smoke:
            SE.release_lock()
    print("HARVEST DONE", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
